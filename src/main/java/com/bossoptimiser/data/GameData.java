package com.bossoptimiser.data;

import com.google.gson.Gson;
import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import java.io.IOException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.io.Reader;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.Collection;
import java.util.Collections;
import java.util.EnumMap;
import java.util.HashMap;
import java.util.HashSet;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Set;

/**
 * Immutable, versioned catalogue of items, monsters, spells, weapon styles and ammunition
 * compatibility. Everything in here comes from bundled JSON resources generated by
 * {@code scripts/update-data.mjs}; nothing is fetched at runtime and nothing is invented in code.
 */
public final class GameData
{
	public static final String RESOURCE_ROOT = "/com/bossoptimiser/items/";

	private final DataVersion version;
	private final Map<Integer, ItemDef> itemsById = new HashMap<>();
	private final Map<String, List<ItemDef>> itemsByName = new HashMap<>();
	private final Map<ItemSlot, List<ItemDef>> itemsBySlot = new EnumMap<>(ItemSlot.class);
	private final Map<Integer, Integer> aliases = new HashMap<>();
	private final Map<Integer, MonsterDef> monstersById = new HashMap<>();
	private final Map<Integer, List<MonsterDef>> monsterVersionsById = new HashMap<>();
	private final Map<String, List<MonsterDef>> monstersByName = new HashMap<>();
	private final Map<String, SpellDef> spellsByName = new HashMap<>();
	private final List<SpellDef> spells = new ArrayList<>();
	private final Map<String, List<CombatStyle>> stylesByCategory = new HashMap<>();
	/** weapon id -> allowed ammunition ids. An empty set means the weapon needs no ammunition slot item. */
	private final Map<Integer, Set<Integer>> ammoByWeapon = new HashMap<>();

	private GameData(DataVersion version)
	{
		this.version = version;
		for (ItemSlot s : ItemSlot.values())
		{
			itemsBySlot.put(s, new ArrayList<>());
		}
	}

	public static GameData load(Gson gson) throws IOException
	{
		JsonObject items = read(gson, "items.json");
		JsonObject meta = items.getAsJsonObject("meta");
		DataVersion version = new DataVersion(
			meta.get("schema").getAsInt(),
			meta.get("generated").getAsString(),
			meta.get("source").getAsString(),
			meta.get("sourceRef").getAsString(),
			meta.get("licence").getAsString());
		GameData data = new GameData(version);
		data.loadItems(items);
		data.loadMonsters(read(gson, "monsters.json"));
		data.loadSpells(read(gson, "spells.json"));
		data.loadStyles(read(gson, "weapon-styles.json"));
		data.loadAmmo(read(gson, "ammo.json"));
		return data;
	}

	private static JsonObject read(Gson gson, String name) throws IOException
	{
		try (InputStream in = GameData.class.getResourceAsStream(RESOURCE_ROOT + name))
		{
			if (in == null)
			{
				throw new IOException("Missing bundled data resource " + name);
			}
			try (Reader r = new InputStreamReader(in, StandardCharsets.UTF_8))
			{
				return gson.fromJson(r, JsonObject.class);
			}
		}
	}

	private void loadItems(JsonObject root)
	{
		for (JsonElement el : root.getAsJsonArray("rows"))
		{
			JsonArray r = el.getAsJsonArray();
			ItemDef def = ItemDef.builder()
				.id(r.get(0).getAsInt())
				.name(r.get(1).getAsString())
				.version(r.get(2).getAsString())
				.slot(ItemSlot.fromKey(r.get(3).getAsString()))
				.category(normaliseCategory(r.get(4).getAsString()))
				.speed(r.get(5).getAsInt())
				.twoHanded(r.get(6).getAsInt() == 1)
				.astab(r.get(7).getAsInt()).aslash(r.get(8).getAsInt()).acrush(r.get(9).getAsInt())
				.amagic(r.get(10).getAsInt()).aranged(r.get(11).getAsInt())
				.dstab(r.get(12).getAsInt()).dslash(r.get(13).getAsInt()).dcrush(r.get(14).getAsInt())
				.dmagic(r.get(15).getAsInt()).dranged(r.get(16).getAsInt())
				.str(r.get(17).getAsInt()).rstr(r.get(18).getAsInt()).mdmg(r.get(19).getAsInt())
				.prayer(r.get(20).getAsInt())
				.build();
			itemsById.put(def.getId(), def);
			itemsByName.computeIfAbsent(def.getName(), k -> new ArrayList<>()).add(def);
			itemsBySlot.get(def.getSlot()).add(def);
		}
		for (Map.Entry<String, JsonElement> e : root.getAsJsonObject("aliases").entrySet())
		{
			aliases.put(Integer.parseInt(e.getKey()), e.getValue().getAsInt());
		}
	}

	private static String normaliseCategory(String category)
	{
		// The source data contains a lower-case "blunt" alongside "Blunt".
		if (category.isEmpty())
		{
			return category;
		}
		return category.substring(0, 1).toUpperCase(Locale.ROOT) + category.substring(1);
	}

	private void loadMonsters(JsonObject root)
	{
		for (JsonElement el : root.getAsJsonArray("monsters"))
		{
			JsonObject m = el.getAsJsonObject();
			JsonArray sk = m.getAsJsonArray("skills");
			JsonArray off = m.getAsJsonArray("offensive");
			JsonArray def = m.getAsJsonArray("defensive");
			JsonElement weak = m.get("weakness");
			MonsterDef monster = MonsterDef.builder()
				.id(m.get("id").getAsInt())
				.name(m.get("name").getAsString())
				.version(m.get("version").getAsString())
				.combatLevel(intOr(m.get("level"), 0))
				.size(intOr(m.get("size"), 1))
				.speed(intOr(m.get("speed"), 4))
				.attackStyles(strings(m.getAsJsonArray("styles")))
				.maxHitText(m.get("maxHit").getAsString())
				.attackLevel(sk.get(0).getAsInt()).strengthLevel(sk.get(1).getAsInt())
				.defenceLevel(sk.get(2).getAsInt()).magicLevel(sk.get(3).getAsInt())
				.rangedLevel(sk.get(4).getAsInt()).hitpoints(sk.get(5).getAsInt())
				.offAttack(off.get(0).getAsInt()).offStrength(off.get(1).getAsInt())
				.offMagic(off.get(2).getAsInt()).offMagicStrength(off.get(3).getAsInt())
				.offRanged(off.get(4).getAsInt()).offRangedStrength(off.get(5).getAsInt())
				.defStab(def.get(0).getAsInt()).defSlash(def.get(1).getAsInt()).defCrush(def.get(2).getAsInt())
				.defMagic(def.get(3).getAsInt()).defLight(def.get(4).getAsInt())
				.defStandard(def.get(5).getAsInt()).defHeavy(def.get(6).getAsInt())
				.flatArmour(def.get(7).getAsInt())
				.attributes(strings(m.getAsJsonArray("attributes")))
				.slayerMonster(m.get("slayer").getAsBoolean())
				.weaknessElement(weak == null || weak.isJsonNull() ? null : weak.getAsJsonArray().get(0).getAsString())
				.weaknessSeverity(weak == null || weak.isJsonNull() ? 0 : weak.getAsJsonArray().get(1).getAsInt())
				.build();
			// The source lists some monsters several times with the same id; the first entry wins.
			monstersById.putIfAbsent(monster.getId(), monster);
			monsterVersionsById.computeIfAbsent(monster.getId(), k -> new ArrayList<>()).add(monster);
			monstersByName.computeIfAbsent(monster.getName(), k -> new ArrayList<>()).add(monster);
		}
	}

	private static int intOr(JsonElement el, int fallback)
	{
		return el == null || el.isJsonNull() ? fallback : el.getAsInt();
	}

	private static List<String> strings(JsonArray arr)
	{
		List<String> out = new ArrayList<>();
		if (arr != null)
		{
			for (JsonElement e : arr)
			{
				if (!e.isJsonNull())
				{
					out.add(e.getAsString());
				}
			}
		}
		return Collections.unmodifiableList(out);
	}

	private void loadSpells(JsonObject root)
	{
		for (JsonElement el : root.getAsJsonArray("spells"))
		{
			JsonObject s = el.getAsJsonObject();
			JsonElement element = s.get("element");
			SpellDef spell = new SpellDef(
				s.get("name").getAsString(),
				s.get("maxHit").getAsInt(),
				s.get("spellbook").getAsString(),
				element == null || element.isJsonNull() ? null : element.getAsString());
			spells.add(spell);
			spellsByName.put(spell.getName(), spell);
		}
	}

	private void loadStyles(JsonObject root)
	{
		for (Map.Entry<String, JsonElement> e : root.getAsJsonObject("styles").entrySet())
		{
			List<CombatStyle> styles = new ArrayList<>();
			for (JsonElement el : e.getValue().getAsJsonArray())
			{
				JsonObject s = el.getAsJsonObject();
				CombatStyle style = new CombatStyle(
					s.get("name").getAsString(),
					AttackType.fromKey(s.get("type").getAsString()),
					s.get("stance").getAsString());
				if (!styles.contains(style))
				{
					styles.add(style);
				}
			}
			stylesByCategory.put(normaliseCategory(e.getKey()), Collections.unmodifiableList(styles));
		}
	}

	private void loadAmmo(JsonObject root)
	{
		List<Set<Integer>> groups = new ArrayList<>();
		for (JsonElement g : root.getAsJsonArray("groups"))
		{
			Set<Integer> ids = new HashSet<>();
			for (JsonElement id : g.getAsJsonArray())
			{
				ids.add(id.getAsInt());
			}
			groups.add(Collections.unmodifiableSet(ids));
		}
		for (Map.Entry<String, JsonElement> e : root.getAsJsonObject("weapons").entrySet())
		{
			ammoByWeapon.put(Integer.parseInt(e.getKey()), groups.get(e.getValue().getAsInt()));
		}
	}

	public DataVersion getVersion()
	{
		return version;
	}

	/** Maps cosmetic / locked / degraded variants onto the item whose statistics they share. */
	public int canonicalId(int itemId)
	{
		Integer canonical = aliases.get(itemId);
		return canonical == null ? itemId : canonical;
	}

	/** Looks an item up by id, following variant aliases. Returns null for non-equipable or unknown items. */
	public ItemDef item(int itemId)
	{
		ItemDef def = itemsById.get(itemId);
		if (def == null)
		{
			def = itemsById.get(canonicalId(itemId));
		}
		return def;
	}

	/** The canonical definition for an id: the alias target when one exists. */
	public ItemDef canonicalItem(int itemId)
	{
		ItemDef def = itemsById.get(canonicalId(itemId));
		return def != null ? def : itemsById.get(itemId);
	}

	public ItemDef itemByName(String name)
	{
		return itemByName(name, null);
	}

	/**
	 * Finds an item by exact name. When several versions exist the charged / usable one is preferred
	 * unless a specific version is requested.
	 */
	public ItemDef itemByName(String name, String versionName)
	{
		List<ItemDef> matches = itemsByName.get(name);
		if (matches == null)
		{
			return null;
		}
		ItemDef best = null;
		for (ItemDef d : matches)
		{
			if (versionName != null)
			{
				if (d.getVersion().equals(versionName))
				{
					return d;
				}
				continue;
			}
			if (best == null || rank(d) < rank(best))
			{
				best = d;
			}
		}
		return best;
	}

	private int rank(ItemDef d)
	{
		int r = d.isDepleted() ? 100 : 0;
		if (aliases.containsKey(d.getId()))
		{
			r += 10;
		}
		if ("Charged".equals(d.getVersion()) || d.getVersion().isEmpty() || "Normal".equals(d.getVersion()))
		{
			r -= 1;
		}
		return r;
	}

	public Collection<ItemDef> items()
	{
		return Collections.unmodifiableCollection(itemsById.values());
	}

	public List<ItemDef> itemsInSlot(ItemSlot slot)
	{
		return Collections.unmodifiableList(itemsBySlot.get(slot));
	}

	public MonsterDef monster(int id)
	{
		return monstersById.get(id);
	}

	/**
	 * A monster by id and version. Some ids are shared by several versions (for example a quest and a
	 * post-quest boss); without a version the first listed entry is returned.
	 */
	public MonsterDef monster(int id, String versionName)
	{
		if (versionName == null || versionName.isEmpty())
		{
			return monster(id);
		}
		for (MonsterDef m : monsterVersionsById.getOrDefault(id, Collections.emptyList()))
		{
			if (versionName.equals(m.getVersion()))
			{
				return m;
			}
		}
		return null;
	}

	public MonsterDef monster(String name, String versionName)
	{
		List<MonsterDef> list = monstersByName.get(name);
		if (list == null)
		{
			return null;
		}
		for (MonsterDef m : list)
		{
			if (versionName == null || versionName.isEmpty() || m.getVersion().equals(versionName))
			{
				return m;
			}
		}
		return null;
	}

	public SpellDef spell(String name)
	{
		return spellsByName.get(name);
	}

	public List<SpellDef> spells()
	{
		return Collections.unmodifiableList(spells);
	}

	public List<CombatStyle> stylesFor(ItemDef weapon)
	{
		String category = weapon == null ? "Unarmed" : weapon.getCategory();
		List<CombatStyle> styles = stylesByCategory.get(category);
		if (styles == null)
		{
			styles = stylesByCategory.get("Unarmed");
		}
		return styles == null ? Collections.emptyList() : styles;
	}

	/**
	 * @return null when the weapon does not appear in the ammunition table (it fires without an
	 * ammunition-slot item, or is not a ranged weapon); otherwise the set of ammunition ids it accepts.
	 */
	/** True for arrows, bolts and javelins: items some ranged weapon fires from the ammunition slot. */
	public boolean isAmmunition(int itemId)
	{
		for (Set<Integer> set : ammoByWeapon.values())
		{
			if (set.contains(itemId))
			{
				return true;
			}
		}
		return false;
	}

	public Set<Integer> ammoFor(ItemDef weapon)
	{
		if (weapon == null)
		{
			return null;
		}
		Set<Integer> set = ammoByWeapon.get(weapon.getId());
		return set == null || set.isEmpty() ? null : set;
	}
}
